		-- 5.Magnitude Analysis
        
-- Find total customers by coutries

SELECT 
    country, COUNT(DISTINCT customer_key) AS total_customers
FROM
    customers
GROUP BY country
ORDER BY total_customers DESC;

-- Find total customers by gender

SELECT 
    gender, COUNT(DISTINCT customer_key) AS total_customers
FROM
    customers
GROUP BY gender
ORDER BY total_customers DESC;

-- Find total products by category

SELECT 
    category, COUNT(DISTINCT product_key) AS total_products
FROM
    products
GROUP BY category
ORDER BY total_products DESC;

-- Find the average cost of each category

SELECT 
    category, AVG(cost) AS avg_cost
FROM
    products
GROUP BY category
ORDER BY avg_cost DESC;

-- Find the total revenue generated by each category

SELECT 
    p.category, SUM(s.sales_amount) AS total_revenue
FROM
    products p
	 JOIN
    sales s ON p.product_key = s.product_key
GROUP BY category
ORDER BY total_revenue DESC;

-- What is the total revenue generated from each customer?

SELECT 
	c.customer_key,
    c.first_name,
    c.last_name,
    SUM(s.sales_amount) AS total_revenue
FROM
    customers c
       JOIN
    sales s ON s.customer_key = c.customer_key
GROUP BY c.customer_key, c.first_name , c.last_name
ORDER BY total_revenue DESC;

-- What is the distribution of quantity sold by countries?

SELECT 
    c.country, SUM(s.quantity) AS quantity_sold
FROM
    customers c
        JOIN
    sales s ON c.customer_key = s.customer_key
GROUP BY c.country
ORDER BY quantity_sold DESC;



		-- 6. Ranking Analysis

-- Which 5 products generate the highest revenue?

SELECT
    p.product_name, SUM(s.sales_amount) AS total_revenue
FROM
    products p
        JOIN
    sales s ON p.product_key = s.product_key
GROUP BY p.product_name
ORDER BY total_revenue DESC
LIMIT 5;

-- What are the 5 worst performing products in terms of sales

SELECT
    p.product_name, SUM(s.sales_amount) AS total_revenue
FROM
    products p
        JOIN
    sales s ON p.product_key = s.product_key
GROUP BY p.product_name
ORDER BY total_revenue
LIMIT 5;

-- Using Window function

SELECT * FROM
(SELECT
    RANK() OVER (ORDER BY SUM(s.sales_amount)) AS ranking,
    p.product_name,
    SUM(s.sales_amount) AS total_revenue
FROM
    products p
        JOIN
    sales s ON p.product_key = s.product_key
GROUP BY p.product_name) a
WHERE ranking <= 5;

-- Find the top 10 customers who have generated the highest revenue

SELECT * FROM
(SELECT
RANK() OVER (ORDER BY SUM(s.sales_amount) DESC) AS ranking,
c.customer_key, c.first_name, c.last_name,
SUM(s.sales_amount) AS total_revenue
FROM customers c
JOIN sales s on c.customer_key = s.customer_key
GROUP BY c.customer_key, c.first_name, c.last_name) a
WHERE ranking <= 10;

-- Find the top 3 customers with fewest orders placed

SELECT * FROM
(SELECT
RANK() OVER (ORDER BY COUNT(s.order_number)) AS ranking,
c.customer_key, c.first_name, c.last_name,
COUNT(DISTINCT s.order_number) AS total_orders
FROM customers c
JOIN sales s on c.customer_key = s.customer_key
GROUP BY c.customer_key, c.first_name, c.last_name) a
WHERE ranking <= 3;