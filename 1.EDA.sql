		-- 3.Dates Exploration
            
-- Find the first and last order date
-- How many years of sales data is available

SELECT
MIN(order_date) as first_order_date,
MAX(order_date) as last_order_date,
TIMESTAMPDIFF(MONTH, MIN(order_date), MAX(order_date)) as order_range_months
FROM sales;

-- Find the youngest and the oldest customer

SELECT
MAX(birthdate) AS youngest_customer_bd,
TIMESTAMPDIFF(YEAR, MAX(birthdate), CURDATE()) AS youngest_customer_age,
MIN(birthdate) AS oldest_customer_bd,
TIMESTAMPDIFF(YEAR, MIN(birthdate), CURDATE()) AS oldest_customer_age
FROM customers;


